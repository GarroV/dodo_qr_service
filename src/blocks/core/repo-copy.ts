// Метка копии репозитория. Порты и имя проекта compose параллельные копии уже разводят
// по себе; тем же способом разводится и имя тестовой базы (T070). Иначе два прогона идут
// в одну базу, подготовка сносит схему целиком, и упавший тест выглядит случайным —
// блок auth наблюдал ровно такое падение, которое не повторилось.
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";

/** Восьми шестнадцатеричных знаков хватает: копий на машине единицы, а имя базы читаемо. */
const ID_LENGTH = 8;

/**
 * Корень этой копии репозитория: каталог с `package.json`, то есть путь этого файла
 * минус `src/blocks/core/`. Считается от собственного модуля, а не от `process.cwd()`:
 * рабочий каталог у прогона, хука и запуска из подкаталога разный, метка копии — нет.
 */
export function repositoryRoot(): string {
  return fileURLToPath(new URL("../../../", import.meta.url));
}

/**
 * Устойчивая метка копии: хэш её абсолютного пути. Одна копия — одно значение между
 * прогонами, две копии — разные значения без единой переменной окружения. Поэтому
 * умолчание работает «из коробки» в свежем клоне, а не требует настройки стенда.
 */
export function repositoryCopyId(root: string = repositoryRoot()): string {
  // Завершающий слэш не меняет копию: `fileURLToPath` для каталога отдаёт путь с ним,
  // а записанный руками путь — без.
  const normalized = root.replace(/\/+$/, "");
  return createHash("sha256")
    .update(normalized)
    .digest("hex")
    .slice(0, ID_LENGTH);
}
