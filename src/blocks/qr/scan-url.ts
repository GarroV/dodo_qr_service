// Ссылка, которая зашита в наклейку станции. Живёт отдельно от рисования кода:
// адрес нужен ещё и экрану (его показывают рядом с кодом при отладке), а картинка
// без адреса не значит ничего.
//
// Публичный маршрут заполнения `/s/<код станции>` строит блок `fill`, но знать его
// адрес обязан тот, кто печатает наклейку: наклейка живёт годами, и переехавший
// маршрут означает переклейку по всей сети. Поэтому префикс записан здесь один раз.

/** Префикс публичного маршрута заполнения (docs/forge/plan.md, «Поверхности»). */
export const STATION_SCAN_PREFIX = "/s/";

/**
 * Абсолютная ссылка на заполнение станции.
 *
 * Абсолютная, а не относительная: код читает камера телефона снаружи браузера —
 * относительный путь ей открыть неоткуда.
 */
export function stationScanUrl(origin: string, code: string): string {
  if (code === "") {
    throw new Error("ссылка станции: код пустой, вести такой наклейке некуда");
  }

  let base: URL;
  try {
    base = new URL(origin);
  } catch {
    throw new Error(`ссылка станции: источник ссылки не адрес — ${origin}`);
  }

  return `${base.origin}${STATION_SCAN_PREFIX}${encodeURIComponent(code)}`;
}
