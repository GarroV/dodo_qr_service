"use server";

import { submitFilling } from "../submit";
import type { SubmitOutcome } from "../submit";

/**
 * Приём заполнения. Серверное действие, а не отдельный обработчик маршрута:
 * действие уходит POST-запросом на тот же адрес `/s/<код станции>` — ровно то,
 * что записано в контракте блока, — а `page.tsx` и `route.ts` в одном сегменте
 * Next иметь не даёт.
 *
 * Тело действия вызывает кто угодно, а не только наш экран: всё, что приходит,
 * проверяется схемой на границе внутри `submitFilling`, здесь проверок нет
 * намеренно — иначе их было бы две в разных местах и они бы разъехались.
 *
 * Время берётся здесь и передаётся дальше явно: так правила приёма проверяются
 * тестами на любой момент времени, а не только «сейчас».
 */
export async function submitFillAction(input: unknown): Promise<SubmitOutcome> {
  return await submitFilling(input, new Date());
}
