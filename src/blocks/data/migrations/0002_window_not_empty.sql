-- Окно чек-листа не может быть пустым (T057). При window_start = window_end условие
-- выбора версии всегда ложно: чек-лист молча не открывается ни на одной станции.
-- Если в базе уже есть такие строки, миграция падает — это правильно: пустое окно
-- чинит методист осознанно, а не миграция вслепую.
ALTER TABLE "checklists" ADD CONSTRAINT "checklists_window_not_empty" CHECK (window_start <> window_end);
