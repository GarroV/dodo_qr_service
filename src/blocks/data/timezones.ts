// Список часовых поясов, которые знает САМА база.
//
// Пояс пиццерии применяет PostgreSQL внутри выборки (D026), и имя, которого он не
// знает, роняет всю выборку целиком — не строку, а запрос. Для запроса по одной
// станции это отказ одной пиццерии; для запроса по всей сети это отказ экрана
// управляющего из-за одной сломанной строки. Поэтому выборки, идущие по многим
// пиццериям сразу, переводят время не по `stores.timezone`, а по имени, найденному
// в этом представлении: незнакомый пояс тогда даёт NULL, а не исключение.
//
// Запись такого имени продукт не допускает (`assertKnownTimezone` в блоке catalog,
// T062), но проверка при записи не вечна: обновление PostgreSQL уносит с собой
// упразднённые имена зон, и вчера правильное значение завтра оказывается неизвестным.
import { pgTable, text } from "drizzle-orm/pg-core";

/**
 * Системное представление PostgreSQL. Не наша таблица: в миграциях его нет и быть
 * не может — оно приходит вместе с базой, поэтому описано отдельно от схемы продукта.
 */
export const timezoneNames = pgTable("pg_timezone_names", {
  name: text("name").notNull(),
});
