// Единственное подключение продукта к базе. Все блоки ходят в данные через слой data,
// а слой data — через этот пул: одно место, где живут строка подключения, её проверка
// и пределы, за которые пул не выходит под нагрузкой.
import { drizzle } from "drizzle-orm/node-postgres";
import type { NodePgDatabase } from "drizzle-orm/node-postgres";
import { Pool } from "pg";

import * as schema from "./schema";

export type Database = NodePgDatabase<typeof schema>;

// Next в режиме разработки перезагружает модули на каждую правку. Без общего хранилища
// каждая перезагрузка открывала бы новый пул, и соединения кончились бы за день работы.
interface PoolHolder {
  dodoQrPool?: Pool;
}
const holder = globalThis as PoolHolder;

let database: Database | undefined;

function connectionString(): string {
  const url = process.env["DATABASE_URL"];
  if (url === undefined || url === "") {
    throw new Error("Нет DATABASE_URL: скопируйте .env.example в .env");
  }
  return url;
}

// Пределы пула, а не настройки по умолчанию: маршрут заполнения открыт в интернет, и под
// всплеском продукт обязан быстро отказывать, а не копить очередь. У драйвера по умолчанию
// не ограничено ни ожидание свободного соединения, ни время выполнения запроса — то есть
// запросы висят, пока сотрудник смотрит на спиннер, а соединения не возвращаются в пул.
const POOL_LIMITS = {
  // Потолок времени запроса на стороне базы. Ни один запрос продукта не идёт секундами:
  // самая тяжёлая выборка — лента заполнений одной станции, ограниченная 200 строками
  // и составным индексом. Десять секунд — уже не «медленно», а «зависло» (блокировка,
  // забытое условие): такой запрос база снимает сама, и соединение возвращается в пул.
  statement_timeout: 10_000,
  // Ожидание свободного соединения. Штатно оно занимает десятки миллисекунд, поэтому три
  // секунды — стократный запас и одновременно быстрый отказ: сотрудник видит понятную
  // ошибку и пересканирует код, а очередь не растёт.
  connectionTimeoutMillis: 3_000,
  // Предел соединений задан явно, а не унаследован у драйвера: совпадение с его нынешним
  // умолчанием — не решение, и обновление драйвера не должно менять нагрузку на базу молча.
  // Внутренний инструмент сети пиццерий — это десятки сканирований в минуту на пересменке,
  // десяти соединений хватает многократно, а бюджет PostgreSQL (100 по умолчанию) остаётся
  // свободен для миграций, psql и второго экземпляра приложения во время выкладки.
  max: 10,
} as const;

export function getDb(): Database {
  if (database === undefined) {
    holder.dodoQrPool ??= new Pool({
      connectionString: connectionString(),
      ...POOL_LIMITS,
    });
    database = drizzle(holder.dodoQrPool, { schema });
  }
  return database;
}
