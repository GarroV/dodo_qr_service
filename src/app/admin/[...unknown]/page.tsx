import { notFound } from "next/navigation";

/**
 * Ловушка неизвестных адресов админки.
 *
 * Без неё Next отвечает 404 раньше, чем отрабатывает охрана в `layout.tsx`, и перебор
 * адресов рассказывает гостю, какие разделы в админке есть: существующий даёт переход
 * на вход, несуществующий — 404. Здесь любой неизвестный адрес сначала проходит охрану
 * и только вошедшему превращается в «страница не найдена».
 */
export default function AdminUnknownPage(): never {
  notFound();
}
