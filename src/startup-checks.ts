// Проверка окружения площадки при старте продукта. Зовётся из `src/instrumentation.ts`.
//
// Смысл ровно один: настройка, из-за которой продукт работает неправильно, обязана
// останавливать его при старте, а не всплывать через неделю на экране у методиста
// или молча выключать защиту. Значения переменных запекаются в сборку (D033),
// поэтому «поднялся — значит настроен» здесь дорогого стоит.
import {
  TRUSTED_PROXY_HOPS_VAR,
  trustedProxyHops,
} from "@/blocks/fill/rate-limit";
import { configuredOrigin } from "@/blocks/qr/ui/origin";

/**
 * Проверяет окружение и возвращает то, о чём стоит сказать вслух.
 *
 * Отказ (исключение) — там, где значение задано и негодно. Пустое окружение
 * отказом не считается: свежий клон и сквозные сценарии поднимаются без `.env`.
 */
export function checkStartupConfig(
  env: Record<string, string | undefined>,
): readonly string[] {
  const notes: string[] = [];

  // Бросает, если адрес задан и негоден: иначе первая же наклейка печатается в никуда.
  configuredOrigin(env);

  // Бросает, если число посредников задано и негодно.
  if (trustedProxyHops(env) === 0) {
    notes.push(
      `${TRUSTED_PROXY_HOPS_VAR} не задан: предел на открытие экрана заполнения по клиенту НЕ применяется — ` +
        "заголовку о клиенте без объявленного посредника доверять нечем. " +
        "Отправка заполнений при этом ограничена по-прежнему: по коду станции и по сети целиком",
    );
  }

  return notes;
}
